# ---------------------------------------------------------------- 工具
def read_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def load_env_key():
    with open(ENV_PATH, encoding="utf-8-sig") as f:
        lines = [ln.strip() for ln in f]
    for ln in lines:
        if ln.startswith("TYPESAFE_API_KEY") and "=" in ln:
            return ln.split("=", 1)[1].strip().strip("'\"")
    for ln in lines:  # 兼容: 裸 key 行(无变量名)
        if ln and not ln.startswith("#") and "=" not in ln:
            return ln
    raise SystemExit("TYPESAFE_API_KEY not found in .env")


def assign_ids(samples):
    counters = Counter()
    for s in samples:
        counters[s["task"]] += 1
        s["id"] = "zhft_{}_{:04d}".format(s["task"], counters[s["task"]])
    return samples


# ---------------------------------------------------------------- gen
def cmd_gen():
    rows = []
    for task, spec in TASKS.items():
        buckets = SAMPLES[task]
        pools = [[(cls, t) for t in texts] for cls, texts in buckets.items()]
        counts = {cls: len(t) for cls, t in buckets.items()}
        while any(pools):
            for pool in pools:
                if pool:
                    cls, t = pool.pop(0)
                    rows.append({"task": task, "text": t, "intended": cls})
        print("gen {}: {} {}".format(task, sum(counts.values()), dict(counts)))
    with open(RAW, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("wrote {} rows -> {}".format(len(rows), RAW))


# ---------------------------------------------------------------- label
def call_jev(key, text, spec, session):
    body = {
        "state": json.dumps({"text": text}, ensure_ascii=False),
        "model": "jev-latest",
        "questions": {
            "d": {"type": "choice", "instructions": spec["instructions"], "criteria": spec["criteria"]}
        },
    }
    last_err = ""
    for attempt in range(6):  # 首次 + 最多5次重试
        try:
            r = session.post(
                API_URL,
                headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"},
                json=body,
                timeout=(10, 90),
            )
            if r.status_code == 200:
                return r.json()["answers"]["d"]["probabilities"]
            if r.status_code == 429 or r.status_code >= 500:
                last_err = "HTTP {}".format(r.status_code)
            else:
                raise RuntimeError("HTTP {}: {}".format(r.status_code, r.text[:200]))
        except Exception as e:  # 超时/连接错误/4xx
            last_err = "{}: {}".format(type(e).__name__, str(e)[:150])
            if "HTTP 4" in last_err and "HTTP 429" not in last_err:
                break  # 非429的4xx不重试
        if attempt < 5:
            time.sleep(random.uniform(15, 30))
    raise RuntimeError("retries exhausted, last=" + last_err)


def cmd_label(limit):
    import requests

    os.environ["https_proxy"] = "http://127.0.0.1:7890"
    os.environ["HTTPS_PROXY"] = "http://127.0.0.1:7890"
    key = load_env_key()
    samples = read_jsonl(RAW)
    assign_ids(samples)
    done = set()
    if os.path.exists(DONE):
        done = {ln.strip() for ln in open(DONE, encoding="utf-8") if ln.strip()}
    if os.path.exists(LABELS):  # 崩溃窗口兜底: 有标签即视为已完成
        done |= {l["id"] for l in read_jsonl(LABELS)}
    pending = [s for s in samples if s["id"] not in done]
    if limit:
        pending = pending[:limit]
    print("total={} done_before={} pending={}".format(len(samples), len(done), len(pending)))
    if not pending:
        return

    lock = threading.Lock()
    stats = {"ok": 0, "fail": 0}

    def work(s):
        spec = TASKS[s["task"]]
        session = requests.Session()
        try:
            probs = call_jev(key, s["text"], spec, session)
        except Exception as e:
            with lock:
                stats["fail"] += 1
                with open(FAILS, "a", encoding="utf-8", newline="\n") as f:
                    f.write(json.dumps({"id": s["id"], "error": str(e)[:300]}, ensure_ascii=False) + "\n")
            return
        with lock:
            stats["ok"] += 1
            with open(LABELS, "a", encoding="utf-8", newline="\n") as f:
                f.write(json.dumps({"id": s["id"], "task": s["task"], "probs": probs}, ensure_ascii=False) + "\n")
            with open(DONE, "a", encoding="utf-8", newline="\n") as f:
                f.write(s["id"] + "\n")

    t0 = time.monotonic()
    with ThreadPoolExecutor(max_workers=2) as ex:
        futs = [ex.submit(work, s) for s in pending]
        for i, fu in enumerate(as_completed(futs), 1):
            if i % 25 == 0 or i == len(pending):
                el = time.monotonic() - t0
                print("progress {}/{} ok={} fail={} {:.0f}s".format(i, len(pending), stats["ok"], stats["fail"], el), flush=True)
    print("label done: ok={} fail={}".format(stats["ok"], stats["fail"]))


