def normalize(probs, criteria):
    dropped = [k for k in probs if k not in criteria]
    p = {k: float(probs.get(k, 0.0)) for k in criteria}
    total = sum(p.values())
    if total <= 0:
        raise ValueError("no probability mass on criteria: " + json.dumps(probs, ensure_ascii=False)[:200])
    p = {k: v / total for k, v in p.items()}
    r = {k: round(v, 4) for k, v in p.items()}
    resid = round(1.0 - sum(r.values()), 4)
    if resid:
        km = max(r, key=lambda k: r[k])
        r[km] = round(r[km] + resid, 4)
    if abs(sum(r.values()) - 1.0) > 1e-6:
        raise ValueError("sum != 1 after rounding: {}".format(sum(r.values())))
    return r, dropped


def cmd_build():
    samples = read_jsonl(RAW)
    assign_ids(samples)
    intended = {s["id"]: s["intended"] for s in samples}
    if not os.path.exists(LABELS):
        raise SystemExit("no labels file: " + LABELS)
    labels = {l["id"]: l["probs"] for l in read_jsonl(LABELS)}

    recs, missing, dropped_total, bad = [], [], Counter(), 0
    for s in samples:
        if s["id"] not in labels:
            missing.append(s["id"])
            continue
        spec = TASKS[s["task"]]
        gold, dropped = normalize(labels[s["id"]], spec["criteria"])
        dropped_total[s["task"]] += len(dropped)
        recs.append({
            "id": s["id"],
            "state_id": s["id"],
            "family_id": spec["family_id"],
            "split": "train",
            "state": json.dumps({"text": s["text"]}, ensure_ascii=False),
            "questions": {spec["qid"]: {"type": "choice", "instructions": spec["instructions"], "criteria": spec["criteria"]}},
            "gold_probs": {spec["qid"]: gold},
            "gold_probs_kind": {spec["qid"]: "programmatic_conditional_distribution"},
        })

    # 自检: keys 与 criteria 完全一致, 和=1 (容差 1e-6)
    qid_by_task = {t: sp["qid"] for t, sp in TASKS.items()}
    for rec in recs:
        t = rec["id"].split("_")[1]
        qid = qid_by_task[t]
        assert set(rec["gold_probs"][qid]) == set(TASKS[t]["criteria"]), rec["id"]
        assert abs(sum(rec["gold_probs"][qid].values()) - 1.0) <= 1e-6, rec["id"]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for rec in recs:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    # 统计
    print("== report ==")
    print("output_records={}".format(len(recs)))
    for t in TASKS:
        sub = [r for r in recs if r["id"].startswith("zhft_" + t)]
        if not sub:
            print("{}: 0 records".format(t))
            continue
        argmax_c = Counter()
        agree = 0
        for r in sub:
            qid = qid_by_task[t]
            top = max(r["gold_probs"][qid], key=r["gold_probs"][qid].get)
            argmax_c[top] += 1
            if top == intended[r["id"]]:
                agree += 1
        print("{}: n={} argmax={} agree_with_intended={}/{}".format(t, len(sub), dict(argmax_c), agree, len(sub)))
        if dropped_total[t]:
            print("  note: dropped non-criteria keys on {} rows".format(dropped_total[t]))
    print("failed_ids={}".format(len(missing)))
    if missing:
        print("failed list: " + ", ".join(missing[:20]) + (" ..." if len(missing) > 20 else ""))
    print("== 3 sample rows ==")
    for rid in ("zhft_intent_0001", "zhft_sentiment_0001", "zhft_urgency_0001"):
        rec = next((r for r in recs if r["id"] == rid), None)
        if rec:
            print(json.dumps(rec, ensure_ascii=False))


